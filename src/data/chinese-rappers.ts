function inferChineseName(rapper: ChineseRapperSeed) {
  const chinesePattern = /[\u4e00-\u9fff]/;

  if (chinesePattern.test(rapper.name)) {
    return rapper.name;
  }

  if (rapper.alias && chinesePattern.test(rapper.alias)) {
    return rapper.alias;
  }

  return rapper.chineseName;
}

function inferLabels(rapper: ChineseRapperSeed) {
  const labels = rapper.labels ?? rapper.tags.filter((tag) => labelTags.has(tag));
  return labels.length > 0 ? labels : undefined;
}

